import fs from "node:fs";
import { basename, join } from "node:path";

/**
 * An app that landfall writes the Dockerfile for:
 * how it builds and starts (each editable), and the port it listens on by default.
 * Commands run in a shell with PORT set to the site's port.
 */
export interface Runtime {
  /** The language, e.g. Node.js, Python, Go, Java. */
  name: string;
  /** The framework or build tool, e.g. Django, Spring Boot (Maven). */
  tool?: string;
  build?: string;
  start: string;
  port: number;
  /** Left out of the upload and the image: local environments and build output (made again inside it). */
  ignore: string[];
  /** What the app needs that landfall cannot know, e.g. a secret in the site's .env. */
  note?: string;
  /** The variable in the site's .env the note asks for: once there, the note is not repeated. */
  secret?: string;
  /** What the project has to change before it deploys: deploy stops with it. */
  fix?: string;
  /** Folders in the container whose files outlive a deploy (named volumes), e.g. a SQLite database. */
  volumes?: string[];
  dockerfile(o: { build?: string; start: string; port: number }): string;
}

export const files = (cwd: string) => {
  const has = (f: string) => fs.existsSync(join(cwd, f));
  const read = (f: string) => {
    try {
      return fs.readFileSync(join(cwd, f), "utf8");
    } catch {
      return "";
    }
  };
  const list = (dir = ".") => {
    try {
      return fs.readdirSync(join(cwd, dir));
    } catch {
      return [];
    }
  };
  const first = (names: string[]) => {
    const name = names.find(has);
    return name ? read(name) : "";
  };
  let pkg: any;
  return {
    has,
    read,
    list,
    first,
    /** package.json, parsed once; {} without one. */
    get pkg(): any {
      try {
        pkg ??= JSON.parse(read("package.json") || "{}");
      } catch {
        pkg = {};
      }
      return pkg;
    },
  };
};
export type Files = ReturnType<typeof files>;

/** The package manager its lockfile names, and how it runs a package.json script. */
export function packageManager(has: (f: string) => boolean, bun = false, declared?: string) {
  // The lockfile says what installed the project; else package.json's packageManager (`pnpm@10.4.1`).
  const named = declared?.match(/^(pnpm|yarn|npm|bun)@/)?.[1];
  const name =
    bun || has("bun.lock") || has("bun.lockb")
      ? "bun"
      : has("pnpm-lock.yaml")
        ? "pnpm"
        : has("yarn.lock")
          ? "yarn"
          : has("package-lock.json")
            ? "npm"
            : (named ?? "npm");
  const run = (script: string) =>
    name === "bun" ? `bun run ${script}` : name === "npm" ? (script === "start" ? "npm start" : `npm run ${script}`) : `${name} ${script}`;
  /** Adds a dev dependency. */
  const add = (pkg: string) => (name === "npm" ? `npm install -D ${pkg}` : `${name} add -${name === "bun" ? "d" : "D"} ${pkg}`);
  return { name, run, add };
}

export const head = (tool?: string) => `# Generated by landfall${tool ? ` for ${tool}` : ""}: \`lf init\` writes it into the project, to change it there.`;
/** PORT and any variables of the app's own, then the port and the start command. */
export const tail = (o: { port: number; start: string }, env = "") =>
  [`ENV ${env}${env && " "}PORT=${o.port}`, `EXPOSE ${o.port}`, `CMD ${o.start}`, ""].join("\n");

/**
 * The stage that installs a package.json's dependencies: Node.js from .nvmrc / .node-version with the lockfile's
 * package manager, or Bun's image (which answers to `node` too). Dependencies install in a layer of their own, so a
 * redeploy that changes none skips it, unless install scripts or workspaces need the whole project.
 */
/** The Node.js major landfall builds with when the project names none. */
const NODE = "24";
/** Majors still maintained; an engines range without NODE picks the newest of them it allows. */
const NODE_MAJORS = [22, 24, 26];

/**
 * The Node.js major for package.json's engines.node: NODE if the range allows it, else the newest maintained
 * major it does (`>=25` is 26), else the newest it names (`^18`). Undefined without a range or for one it cannot read.
 */
export function nodeMajor(range: unknown): string | undefined {
  if (typeof range !== "string" || !range.trim()) return;
  const v = (s: string) => {
    const [maj, min, pat] = s.replace(/^v/, "").split(".");
    const part = (x?: string) => (x === undefined || /^[x*]$/i.test(x) ? undefined : Number.parseInt(x, 10));
    return [part(maj), part(min), part(pat)] as const;
  };
  const at = (p: readonly (number | undefined)[]) => (p[0] ?? 0) * 1e6 + (p[1] ?? 0) * 1e3 + (p[2] ?? 0);
  // The first version past a partial one: 22 → 23.0.0, 22.4 → 22.5.0.
  const after = (p: readonly (number | undefined)[]) =>
    p[0] === undefined ? Infinity : p[1] === undefined ? (p[0] + 1) * 1e6 : p[2] === undefined ? p[0] * 1e6 + (p[1] + 1) * 1e3 : at(p) + 1;
  const allows = (alt: string, major: number) => {
    let lo = major * 1e6;
    let hi = (major + 1) * 1e6;
    const hyphen = alt.match(/^(\S+)\s+-\s+(\S+)$/);
    const parts = hyphen
      ? [`>=${hyphen[1]}`, `<=${hyphen[2]}`]
      : alt
          .replace(/([<>=^~]+)\s+/g, "$1")
          .split(/\s+/)
          .filter(Boolean);
    for (const c of parts) {
      const [, op = "", ver] = c.match(/^([<>]=?|=|\^|~)?(.+)$/) ?? [];
      const p = v(ver ?? "");
      if (p[0] === undefined && ver !== undefined && !/^[x*]$/i.test(ver)) return false;
      if (op === ">=") lo = Math.max(lo, at(p));
      else if (op === ">") lo = Math.max(lo, after(p));
      else if (op === "<") hi = Math.min(hi, at(p));
      else if (op === "<=") hi = Math.min(hi, after(p));
      else if (op === "^") ((lo = Math.max(lo, at(p))), (hi = Math.min(hi, ((p[0] ?? 0) + 1) * 1e6)));
      else if (op === "~") ((lo = Math.max(lo, at(p))), (hi = Math.min(hi, p[1] === undefined ? after(p) : (p[0] ?? 0) * 1e6 + (p[1] + 1) * 1e3)));
      else ((lo = Math.max(lo, at(p))), (hi = Math.min(hi, after(p))));
    }
    return lo < hi;
  };
  const ok = (m: number) => range.split("||").some((alt) => allows(alt.trim(), m));
  if (ok(Number(NODE))) return NODE;
  const pick = NODE_MAJORS.findLast(ok) ?? Array.from({ length: 21 }, (_, i) => 36 - i).find(ok);
  return pick === undefined ? undefined : String(pick);
}

/** The FROM line of a Node.js (or Bun) image: the version the project names. */
export function nodeFrom(f: Files, bun: boolean, as = "") {
  const major = (f.read(".nvmrc") || f.read(".node-version")).trim().match(/^v?(\d+)/)?.[1] ?? nodeMajor(f.pkg.engines?.node) ?? NODE;
  return (bun ? `FROM oven/bun:${f.pkg.packageManager?.match(/^bun@(\d+(?:\.\d+){0,2})/)?.[1] ?? "1"}-slim` : `FROM node:${major}-slim`) + (as && ` AS ${as}`);
}

export function nodeStage(f: Files, bun: boolean, as = ""): string[] {
  const pkg = f.pkg;
  const pm = packageManager(f.has, bun, pkg.packageManager);
  const lock = ["bun.lock", "bun.lockb", "pnpm-lock.yaml", "yarn.lock", "package-lock.json"].find(f.has);
  const whole =
    !!pkg.workspaces ||
    ["pnpm-workspace.yaml", ".yarnrc.yml", "patches"].some(f.has) ||
    ["preinstall", "install", "postinstall", "prepare"].some((s) => s in (pkg.scripts ?? {}));
  const install = !f.has("package.json")
    ? undefined
    : pm.name === "npm"
      ? lock
        ? "npm ci"
        : "npm install"
      : `${pm.name} install${lock ? " --frozen-lockfile" : ""}`;
  const manifests = ["package.json", lock, ...[".npmrc", ".yarnrc", "bunfig.toml"].filter(f.has)].filter(Boolean);
  return [
    nodeFrom(f, bun, as),
    "WORKDIR /app",
    // Corepack runs the version package.json's packageManager pins; Node.js 25 and later ship without it.
    ...(pm.name !== "npm" && !bun ? [`RUN corepack enable || (npm install -g corepack && corepack enable)`] : []),
    ...(install && !whole ? [`COPY ${manifests.join(" ")} ./`, `RUN ${install}`, "COPY . ."] : ["COPY . .", ...(install ? [`RUN ${install}`] : [])]),
  ];
}
const dockerfile = (lines: (string | false | undefined)[]) => lines.filter((l) => typeof l === "string").join("\n");

/** The start command given, else the `web:` process of a Procfile (Heroku and its kind), which knows best how the app starts. */
const procfile = (f: Files, given?: string) =>
  given ||
  f
    .read("Procfile")
    .match(/^web:\s*(.+)$/m)?.[1]
    .trim();

// ---------------------------------------------------------------- Python

/** Files that commonly define the app object, and how a server names their module. */
const PY_ENTRIES = ["main.py", "app.py", "server.py", "api.py", "asgi.py", "wsgi.py", "app/main.py", "app/__init__.py", "src/main.py", "src/app.py"];
const pyModule = (file: string) =>
  file
    .replace(/\.py$/, "")
    .replace(/\/__init__$/, "")
    .replace(/\//g, ".");

function python(f: Files, given?: string): Runtime | undefined {
  const manifests = ["requirements.txt", "pyproject.toml", "Pipfile", "setup.py"].filter(f.has);
  if (!manifests.length && !f.has("manage.py")) return;
  const deps = manifests.map(f.read).join("\n");
  const dep = (n: string) => new RegExp(`(^|[^\\w-])${n}(?![\\w-])`, "im").test(deps);
  const app = (re: RegExp) => {
    for (const file of PY_ENTRIES) {
      const m = f.read(file).match(new RegExp(`^(\\w+)\\s*(?::\\s*\\w+\\s*)?=\\s*(?:${re.source})\\(`, "m"));
      if (m) return `${pyModule(file)}:${m[1]}`;
    }
  };
  const asgi = (target: string) => `uvicorn ${target} --host 0.0.0.0 --port $PORT --proxy-headers --forwarded-allow-ips '*'`;
  let tool: string | undefined, start: string | undefined, build: string | undefined, note: string | undefined;
  let server: string | undefined;
  if (f.has("manage.py")) {
    tool = "Django";
    const mod =
      f.read("manage.py").match(/DJANGO_SETTINGS_MODULE["']\s*,\s*["']([\w.]+)\.settings/)?.[1] ?? f.list().find((d) => f.has(`${d}/wsgi.py`)) ?? "config";
    const settings = f.read(`${mod.replace(/\./g, "/")}/settings.py`);
    // Channels or another ASGI server: websockets need the ASGI app.
    if (dep("daphne")) start = `daphne -b 0.0.0.0 -p $PORT ${mod}.asgi:application`;
    else if ((dep("channels") || dep("uvicorn")) && f.has(`${mod.replace(/\./g, "/")}/asgi.py`)) [server, start] = ["uvicorn", asgi(`${mod}.asgi:application`)];
    else [server, start] = ["gunicorn", `gunicorn ${mod}.wsgi --bind 0.0.0.0:$PORT`];
    if (/\bSTATIC_ROOT\b/.test(settings)) build = "python manage.py collectstatic --noinput";
    note = "Django serves only the hosts in ALLOWED_HOSTS: add the site's domains to it";
  } else {
    const fw = (["FastAPI", "Starlette", "Litestar", "Flask", "Quart", "Sanic"] as const).find((n) => dep(n.toLowerCase()));
    const target = fw && app(new RegExp(fw));
    if (fw && target) {
      tool = fw;
      if (fw === "Flask") [server, start] = ["gunicorn", `gunicorn ${target} --bind 0.0.0.0:$PORT`];
      else if (fw === "Quart") [server, start] = ["hypercorn", `hypercorn ${target} --bind 0.0.0.0:$PORT`];
      else if (fw === "Sanic") start = `sanic ${target} --host 0.0.0.0 --port $PORT`;
      else [server, start] = ["uvicorn", asgi(target)];
    } else if (dep("streamlit")) {
      const file = ["streamlit_app.py", "app.py", "main.py"].find(f.has);
      if (file) [tool, start] = ["Streamlit", `streamlit run ${file} --server.address 0.0.0.0 --server.port $PORT --server.headless true`];
    }
  }
  start = procfile(f, given) ?? start;
  // Anything else runs its own entry, but only in a folder that is not a Node.js project or a MkDocs site.
  if (!start && !f.has("package.json") && !f.has("mkdocs.yml")) {
    const file = ["main.py", "app.py", "server.py"].find(f.has);
    if (file) start = `python ${file}`;
  }
  if (!start) return;
  const version = f.read(".python-version").match(/^(\d+\.\d+)/)?.[1] ?? "3.13";
  const lock = f.has("uv.lock") ? "uv" : f.has("poetry.lock") ? "poetry" : f.has("Pipfile") ? "pipenv" : f.has("requirements.txt") ? "pip" : "project";
  const pip = lock === "uv" ? "uv pip install" : "pip install --no-cache-dir";
  // The server the start command names, when the dependencies leave it out.
  const extra = server && start.startsWith(server) && !dep(server) ? `RUN ${pip} ${server}` : undefined;
  return {
    name: "Python",
    tool,
    build,
    start,
    note,
    port: 8000,
    ignore: [".git", ".venv", "venv", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"],
    dockerfile: (o) =>
      dockerfile([
        head(tool ?? "Python"),
        `FROM python:${version}-slim`,
        "ENV PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1 PIP_DISABLE_PIP_VERSION_CHECK=1",
        "WORKDIR /app",
        ...(lock === "pip"
          ? ["COPY requirements.txt ./", "RUN pip install --no-cache-dir -r requirements.txt", "COPY . ."]
          : lock === "uv"
            ? ["RUN pip install --no-cache-dir uv", "ENV UV_COMPILE_BYTECODE=1 PATH=/app/.venv/bin:$PATH", "COPY . .", "RUN uv sync --frozen --no-dev"]
            : lock === "poetry"
              ? [
                  "RUN pip install --no-cache-dir poetry && poetry config virtualenvs.create false",
                  "COPY . .",
                  "RUN poetry install --only main --no-interaction --no-root",
                ]
              : lock === "pipenv"
                ? ["RUN pip install --no-cache-dir pipenv", "COPY . .", `RUN pipenv install --system${f.has("Pipfile.lock") ? " --deploy" : ""}`]
                : ["COPY . .", ...(f.has("pyproject.toml") || f.has("setup.py") ? ["RUN pip install --no-cache-dir ."] : [])]),
        extra,
        o.build && `RUN ${o.build}`,
        tail(o),
      ]),
  };
}

// ---------------------------------------------------------------- Go

function go(f: Files): Runtime | undefined {
  const mod = f.read("go.mod");
  if (!mod) return;
  // A Hugo site has a go.mod too, but no main package.
  const hasMain = (dir: string) => f.list(dir).some((n) => n.endsWith(".go") && !n.endsWith("_test.go") && /^package main\b/m.test(f.read(join(dir, n))));
  const name = basename(mod.match(/^module\s+(\S+)/m)?.[1] ?? "app");
  const cmds = f.list("cmd").filter((d) => hasMain(`cmd/${d}`));
  const pkg = hasMain(".") ? "." : cmds.length ? `./cmd/${cmds.includes(name) ? name : cmds[0]}` : undefined;
  if (!pkg) return;
  const version = mod.match(/^go\s+(\d+\.\d+)/m)?.[1] ?? "1";
  const fw = Object.entries({ "gin-gonic/gin": "Gin", "labstack/echo": "Echo", "gofiber/fiber": "Fiber", "go-chi/chi": "chi", "gorilla/mux": "Gorilla" }).find(
    ([m]) => mod.includes(m),
  )?.[1];
  const tool = fw ? `Go (${fw})` : "Go";
  return {
    name: "Go",
    tool,
    port: 8080,
    build: `CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -o /out/app ${pkg}`,
    start: "app",
    ignore: [".git"],
    dockerfile: (o) =>
      dockerfile([
        head(tool),
        `FROM golang:${version} AS build`,
        "WORKDIR /src",
        "COPY go.mod go.sum* ./",
        "RUN go mod download",
        "COPY . .",
        // The build writes its binaries to /out: they are all the image takes from it.
        o.build && `RUN mkdir -p /out && ${o.build}`,
        "",
        "FROM alpine:3",
        "RUN apk add --no-cache ca-certificates tzdata",
        "WORKDIR /app",
        // The project's files too: templates and assets the app reads at run time.
        "COPY . .",
        "COPY --from=build /out/ /usr/local/bin/",
        tail(o),
      ]),
  };
}

// ---------------------------------------------------------------- Rust

function rust(f: Files): Runtime | undefined {
  const cargo = f.read("Cargo.toml");
  if (!cargo) return;
  const bin =
    cargo.match(/\[\[bin\]\][^[]*?\bname\s*=\s*"([^"]+)"/)?.[1] ??
    (f.has("src/main.rs") ? cargo.match(/\[package\][^[]*?\bname\s*=\s*"([^"]+)"/)?.[1] : undefined);
  if (!bin) return;
  const fw = Object.entries({ axum: "Axum", "actix-web": "Actix Web", rocket: "Rocket", warp: "warp", poem: "Poem" }).find(([c]) =>
    new RegExp(`^${c}\\s*=`, "m").test(cargo),
  )?.[1];
  const tool = fw ? `Rust (${fw})` : "Rust";
  return {
    name: "Rust",
    tool,
    port: 8080,
    build: `cargo build --release${f.has("Cargo.lock") ? " --locked" : ""} && cp target/release/${bin} /out/`,
    start: bin,
    ignore: [".git", "target"],
    dockerfile: (o) =>
      dockerfile([
        head(tool),
        "FROM rust:1-slim-bookworm AS build",
        "RUN apt-get update && apt-get install -y --no-install-recommends pkg-config libssl-dev && rm -rf /var/lib/apt/lists/*",
        "WORKDIR /src",
        "COPY . .",
        // The build copies its binaries to /out: they are all the image takes from it.
        o.build && `RUN mkdir -p /out && ${o.build}`,
        "",
        "FROM debian:bookworm-slim",
        "RUN apt-get update && apt-get install -y --no-install-recommends ca-certificates libssl3 && rm -rf /var/lib/apt/lists/*",
        "WORKDIR /app",
        "COPY . .",
        "COPY --from=build /out/ /usr/local/bin/",
        tail(o),
      ]),
  };
}

// ---------------------------------------------------------------- Java, Kotlin

/** Java versions with Eclipse Temurin images. */
const JAVA = [8, 11, 17, 21, 25];

function java(f: Files): Runtime | undefined {
  const gradleFile = ["build.gradle.kts", "build.gradle"].find(f.has);
  const maven = !gradleFile && f.has("pom.xml");
  if (!maven && !gradleFile) return;
  // The whole build: a multi-module project names its framework in a module's build file.
  const modules = f.list().filter((d) => f.has(`${d}/pom.xml`) || f.has(`${d}/build.gradle.kts`) || f.has(`${d}/build.gradle`));
  const conf = [maven ? "pom.xml" : gradleFile!, ...modules.flatMap((d) => [`${d}/pom.xml`, `${d}/build.gradle.kts`, `${d}/build.gradle`])]
    .map(f.read)
    .join("\n");
  if (/com\.android\.(application|library)/.test(conf)) return;
  const fw = Object.entries({
    "spring-boot": "Spring Boot",
    quarkus: "Quarkus",
    micronaut: "Micronaut",
    "io.ktor": "Ktor",
    javalin: "Javalin",
    helidon: "Helidon",
    "vertx-": "Vert.x",
    dropwizard: "Dropwizard",
  }).find(([k]) => conf.includes(k))?.[1];
  const found = Number(
    (conf.match(/<(?:java\.version|maven\.compiler\.release|maven\.compiler\.target|release)>\s*(?:1\.)?(\d+)/) ??
      conf.match(/JavaLanguageVersion\.of\(\s*(\d+)/) ??
      conf.match(/jvmToolchain\(\s*(\d+)/) ??
      conf.match(/JavaVersion\.VERSION_(?:1_)?(\d+)/) ??
      conf.match(/(?:source|target)Compatibility\s*=\s*['"]?(?:1\.)?(\d+)/))?.[1] ?? 21,
  );
  const version = JAVA.find((v) => v >= found) ?? JAVA.at(-1)!;
  const wrapper = maven ? f.has("mvnw") : f.has("gradlew");
  const quarkus = fw === "Quarkus";
  const task = fw === "Spring Boot" ? "bootJar" : fw === "Ktor" ? "buildFatJar" : /shadow/i.test(conf) ? "shadowJar" : "build -x test";
  const build = maven ? `${wrapper ? "./mvnw" : "mvn"} -B -DskipTests package` : `${wrapper ? "./gradlew" : "gradle"} --no-daemon ${task}`;
  const out = maven ? "target" : "build";
  // The largest jar the build wrote is the one with its dependencies (Spring Boot, shade, shadow).
  const collect = quarkus
    ? `cp -r "$(find . -type d -name quarkus-app -path '*/${out}/*' | head -n1)" /out/`
    : `cp "$(find . -path '*/${out}/*.jar' -not -path '*/.gradle/*' -not -name '*-plain.jar' -not -name '*-sources.jar' -not -name '*-javadoc.jar' -not -name 'original-*' -not -name '*-tests.jar' | xargs ls -S | head -n1)" /out/app.jar`;
  const kotlin = /kotlin\(|org\.jetbrains\.kotlin/.test(conf);
  const tool = `${fw ?? (kotlin ? "Kotlin" : "Java")} (${maven ? "Maven" : "Gradle"})`;
  return {
    name: kotlin ? "Kotlin" : "Java",
    tool,
    build,
    port: 8080,
    start: quarkus ? "java -jar quarkus-app/quarkus-run.jar" : "java -jar app.jar",
    ignore: [".git", "target", "build", ".gradle", ".idea"],
    dockerfile: (o) =>
      dockerfile([
        head(tool),
        `FROM ${wrapper ? `eclipse-temurin:${version}-jdk` : maven ? `maven:3-eclipse-temurin-${version}` : `gradle:jdk${version}`} AS build`,
        "WORKDIR /src",
        "COPY . .",
        wrapper && `RUN chmod +x ${maven ? "mvnw" : "gradlew"}`,
        o.build && `RUN ${o.build}`,
        `RUN mkdir -p /out && ${collect}`,
        "",
        `FROM eclipse-temurin:${version}-jre`,
        "WORKDIR /app",
        "COPY --from=build /out/ ./",
        // Spring Boot, Quarkus and Micronaut each read their own variable for the port.
        tail(o, `SERVER_PORT=${o.port} QUARKUS_HTTP_PORT=${o.port} MICRONAUT_SERVER_PORT=${o.port} JAVA_TOOL_OPTIONS=-XX:MaxRAMPercentage=75`),
      ]),
  };
}

// ---------------------------------------------------------------- .NET

function dotnet(f: Files): Runtime | undefined {
  const isProj = (n: string) => /\.(cs|fs|vb)proj$/.test(n);
  const top = f.list();
  // A project file at the top, or a solution with its projects one level down (or below src/).
  const bases = top.some(isProj) ? [] : top.some((n) => n.endsWith(".sln") || n.endsWith(".slnx")) ? [".", "src"] : [];
  const candidates = [
    ...top.filter(isProj),
    ...bases.flatMap((base) =>
      f.list(base).flatMap((d) =>
        f
          .list(`${base}/${d}`)
          .filter(isProj)
          .map((n) => `${base === "." ? "" : "src/"}${d}/${n}`),
      ),
    ),
  ].map((p) => ({ p, text: f.read(p) }));
  const found = candidates.find((c) => /Sdk="Microsoft\.NET\.Sdk\.Web"/.test(c.text)) ?? candidates.find((c) => /<OutputType>Exe<\/OutputType>/i.test(c.text));
  if (!found) return;
  const { p: proj, text } = found;
  const web = /Sdk="Microsoft\.NET\.Sdk\.Web"/.test(text);
  const version = text.match(/<TargetFrameworks?>net(\d+\.\d+)/)?.[1] ?? "10.0";
  const name = text.match(/<AssemblyName>([^<]+)</)?.[1] ?? basename(proj).replace(/\.\w+proj$/, "");
  const tool = web ? "ASP.NET Core" : ".NET";
  return {
    name: ".NET",
    tool,
    port: 8080,
    build: `dotnet publish "${proj}" -c Release -o /out`,
    start: `dotnet ${name}.dll`,
    ignore: [".git", "bin", "obj", ".vs"],
    dockerfile: (o) =>
      dockerfile([
        head(tool),
        `FROM mcr.microsoft.com/dotnet/sdk:${version} AS build`,
        "WORKDIR /src",
        "COPY . .",
        // The build publishes to /out: all the image takes from it.
        o.build && `RUN ${o.build}`,
        "",
        `FROM mcr.microsoft.com/dotnet/${web ? "aspnet" : "runtime"}:${version}`,
        "WORKDIR /app",
        "COPY --from=build /out/ ./",
        tail(o, `ASPNETCORE_URLS=http://+:${o.port}`),
      ]),
  };
}

// ---------------------------------------------------------------- Ruby

function ruby(f: Files, given?: string): Runtime | undefined {
  const gems = f.read("Gemfile");
  if (!gems) return;
  const gem = (n: string) => new RegExp(`^\\s*gem\\s+['"]${n}['"]`, "m").test(gems);
  const rails = gem("rails") && f.has("config/application.rb");
  let tool: string | undefined, start: string | undefined;
  // Rails 8's default: SQLite in storage/, which outlives deploys in a volume and is made or migrated on start.
  const sqlite = rails && gem("sqlite3") && /^\s*database:\s*storage\//m.test(f.read("config/database.yml"));
  if (rails) [tool, start] = ["Rails", `${sqlite ? "bundle exec rails db:prepare && " : ""}bundle exec rails server -b 0.0.0.0 -p $PORT`];
  else if (f.has("config.ru")) {
    tool = gem("sinatra") ? "Sinatra" : gem("roda") ? "Roda" : gem("hanami") ? "Hanami" : "Rack";
    start = gem("puma") ? "bundle exec puma -b tcp://0.0.0.0:$PORT" : "bundle exec rackup -o 0.0.0.0 -p $PORT";
  }
  // A Gemfile alone is a Jekyll site or tooling, unless a Procfile starts something.
  start = procfile(f, given) ?? start;
  if (!start) return;
  const version = (f.read(".ruby-version").match(/(\d+\.\d+)/) ?? gems.match(/^ruby\s+['"](\d+\.\d+)/m))?.[1] ?? "3.4";
  const assets = rails && ["propshaft", "sprockets-rails", "importmap-rails", "jsbundling-rails", "cssbundling-rails", "tailwindcss-rails"].some(gem);
  return {
    name: "Ruby",
    tool,
    start,
    port: 3000,
    build: assets ? "SECRET_KEY_BASE_DUMMY=1 bundle exec rails assets:precompile" : undefined,
    secret: rails ? "RAILS_MASTER_KEY" : undefined,
    volumes: sqlite ? ["/app/storage"] : undefined,
    note: rails ? "Rails needs its key: lf deploy -e RAILS_MASTER_KEY=$(cat config/master.key) (once, it stays in the site's .env)" : undefined,
    ignore: [".git", ".bundle", "vendor/bundle", "log", "tmp", "node_modules"],
    dockerfile: (o) =>
      dockerfile([
        head(tool ?? "Ruby"),
        `FROM ruby:${version}-slim`,
        "RUN apt-get update && apt-get install -y --no-install-recommends build-essential git pkg-config libpq-dev libyaml-dev libsqlite3-0 && rm -rf /var/lib/apt/lists/*",
        "WORKDIR /app",
        "ENV RAILS_ENV=production RACK_ENV=production BUNDLE_WITHOUT=development:test RAILS_SERVE_STATIC_FILES=1 RAILS_LOG_TO_STDOUT=1",
        "COPY Gemfile Gemfile.lock* ./",
        "RUN bundle install --jobs 4",
        "COPY . .",
        o.build && `RUN ${o.build}`,
        tail(o),
      ]),
  };
}

// ---------------------------------------------------------------- PHP

function php(f: Files): Runtime | undefined {
  const docroot = f.has("public/index.php") ? "public" : f.has("index.php") ? "" : undefined;
  if (docroot === undefined) return;
  let composer: any = {};
  try {
    composer = JSON.parse(f.read("composer.json") || "{}");
  } catch {}
  const require: Record<string, string> = composer.require ?? {};
  const laravel = f.has("artisan");
  const tool = laravel ? "Laravel" : "symfony/framework-bundle" in require ? "Symfony" : "PHP";
  const version = /(^|[^\d.])7\./.test(require.php ?? "") && !/8\./.test(require.php ?? "") ? "7.4" : "8.4";
  const exts = [
    ...new Set([
      ...Object.keys(require)
        .filter((k) => k.startsWith("ext-"))
        .map((k) => k.slice(4).toLowerCase()),
      "pdo_mysql",
      "pdo_pgsql",
      "opcache",
      "zip",
      "intl",
      "bcmath",
    ]),
  ];
  const hasComposer = f.has("composer.json");
  // Laravel's Vite assets build in a Node.js stage of their own.
  const assets = laravel && !!f.pkg.scripts?.build;
  return {
    name: "PHP",
    tool,
    port: 80,
    build: hasComposer ? "composer install --no-dev --optimize-autoloader --no-interaction" : undefined,
    start: "apache2-foreground",
    secret: laravel ? "APP_KEY" : undefined,
    note: laravel ? "Laravel needs APP_KEY: lf deploy -e APP_KEY=$(php artisan key:generate --show) (once, it stays in the site's .env)" : undefined,
    ignore: [".git", "vendor", "node_modules"],
    dockerfile: (o) =>
      dockerfile([
        head(tool),
        ...(assets ? [...nodeStage(f, false, "assets"), `RUN ${packageManager(f.has, false, f.pkg.packageManager).run("build")}`, ""] : []),
        `FROM php:${version}-apache`,
        "COPY --from=mlocati/php-extension-installer /usr/bin/install-php-extensions /usr/local/bin/",
        `RUN install-php-extensions @composer ${exts.join(" ")}`,
        // .htaccess rewrites (front controllers) work; Apache serves the docroot on PORT.
        [
          "RUN a2enmod rewrite headers",
          "sed -ri 's/AllowOverride None/AllowOverride All/' /etc/apache2/apache2.conf",
          `sed -ri "s/^Listen 80$/Listen ${o.port}/" /etc/apache2/ports.conf`,
          `sed -ri "s/:80>/:${o.port}>/" /etc/apache2/sites-available/000-default.conf`,
          ...(docroot ? ["sed -ri 's!/var/www/html!${APACHE_DOCUMENT_ROOT}!g' /etc/apache2/sites-available/*.conf"] : []),
        ].join(" \\\n && "),
        "WORKDIR /var/www/html",
        "COPY . .",
        assets && "COPY --from=assets /app/public/build ./public/build",
        o.build && `RUN ${o.build}`,
        laravel ? "RUN chown -R www-data:www-data storage bootstrap/cache" : undefined,
        tail(o, docroot ? "APACHE_DOCUMENT_ROOT=/var/www/html/public" : ""),
      ]),
  };
}

// ---------------------------------------------------------------- Elixir

function elixir(f: Files, given?: string): Runtime | undefined {
  const mix = f.read("mix.exs");
  if (!mix) return;
  const phoenix = /:phoenix\b/.test(mix);
  const start = procfile(f, given) ?? (phoenix ? "mix phx.server" : undefined);
  if (!start) return;
  const version = f.read(".tool-versions").match(/^elixir\s+(\d+\.\d+)/m)?.[1] ?? "1.18";
  const tool = phoenix ? "Phoenix" : "Elixir";
  return {
    name: "Elixir",
    tool,
    start,
    port: 4000,
    build: phoenix && /"assets\.deploy"/.test(mix) ? "mix assets.deploy" : undefined,
    secret: phoenix ? "SECRET_KEY_BASE" : undefined,
    note: phoenix ? "Phoenix needs SECRET_KEY_BASE: lf deploy -e SECRET_KEY_BASE=$(mix phx.gen.secret) (once, it stays in the site's .env)" : undefined,
    ignore: [".git", "_build", "deps", ".elixir_ls"],
    dockerfile: (o) =>
      dockerfile([
        head(tool),
        `FROM elixir:${version}`,
        "ENV MIX_ENV=prod PHX_SERVER=true",
        "WORKDIR /app",
        "RUN mix local.hex --force && mix local.rebar --force",
        "COPY mix.exs mix.lock* ./",
        "RUN mix deps.get --only prod && mix deps.compile",
        "COPY . .",
        "RUN mix compile",
        o.build && `RUN ${o.build}`,
        tail(o),
      ]),
  };
}

// ---------------------------------------------------------------- Deno

const DENO_ENTRIES = ["main.ts", "server.ts", "mod.ts", "main.tsx", "main.js", "src/main.ts"];

/** A Lume site: a site generator that builds files, nothing runs. */
export const isLume = (f: Files) => /\blume\b/.test(f.first(["deno.json", "deno.jsonc"]));

function deno(f: Files, given?: string): Runtime | undefined {
  const conf = f.first(["deno.json", "deno.jsonc"]);
  if (!conf && !f.has("deno.lock")) return;
  if (!given && isLume(f)) return;
  const task = (name: string) => conf.match(new RegExp(`"${name}"\\s*:\\s*"([^"]*)"`))?.[1];
  const fresh1 = /\$fresh\/|\/fresh@/.test(conf);
  const tool = /@fresh\/core\b/.test(conf) || fresh1 ? "Fresh" : /\bhono\b/.test(conf) ? "Hono" : /\boak\b/.test(conf) ? "Oak" : undefined;
  const entry = DENO_ENTRIES.find(f.has);
  // Fresh 2 builds a server into _fresh/, Fresh 1 runs main.ts after its build. A start task that watches is for developing.
  // Deno.serve listens on 8000 unless told otherwise.
  const own = task("start");
  const start =
    procfile(f, given) ??
    (tool === "Fresh" && !fresh1
      ? "deno serve -A --port $PORT _fresh/server.js"
      : fresh1 && f.has("main.ts")
        ? "deno run -A main.ts"
        : own && !/--watch\b/.test(own)
          ? "deno task start"
          : entry
            ? `deno run -A ${entry}`
            : undefined);
  if (!start) return;
  const version = (f.read(".dvmrc") || f.read(".tool-versions").match(/^deno\s+(\S+)/m)?.[1] || "").trim().match(/^v?(\d+(?:\.\d+){0,2})/)?.[1] ?? "2";
  return {
    name: "Deno",
    tool,
    start,
    port: 8000,
    build: task("build") !== undefined ? "deno task build" : undefined,
    ignore: [".git", "node_modules", "_fresh"],
    dockerfile: (o) =>
      dockerfile([
        head(tool ?? "Deno"),
        `FROM denoland/deno:${version}`,
        "WORKDIR /app",
        "COPY . .",
        // Fetches what deno.json (and a package.json) imports, so nothing downloads at start.
        "RUN deno install",
        o.build && `RUN ${o.build}`,
        tail(o),
      ]),
  };
}

/**
 * An app in Deno or another language than JavaScript, by the files its build tool keeps.
 * The order settles mixed folders: Laravel, Rails or Django with a package.json for their assets.
 */
export function detectRuntime(cwd: string, start?: string): Runtime | undefined {
  const f = files(cwd);
  for (const detect of [deno, java, go, rust, dotnet, elixir, php, python, ruby]) {
    const r = detect(f, start);
    if (r) return r;
  }
}
